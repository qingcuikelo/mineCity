/** Small mesh for the bulldozer icon. */
export function buildDozerIcon() {
  const m = new Mesh();
  const dark = M.flat(M.col(C.grey3));
  m.box(14, 14, 0, 24, 46, 7, dark);
  m.box(40, 14, 0, 50, 46, 7, dark);
  m.box(16, 20, 7, 48, 42, 20, M.metalRib(M.col(C.gold), { rib: 4, seed: 901 }));
  m.box(30, 24, 20, 46, 38, 32, {
    xp: M.flat(M.col(C.teal2)), yp: M.flat(M.col(C.teal2)),
    xn: M.flat(M.col(C.gold)), yn: M.flat(M.col(C.gold)), top: M.flat(M.col(C.gold)),
  });
  m.box(10, 8, 0, 16, 52, 14, M.flat(M.col(C.grey5)));
  m.box(12, 10, 14, 18, 50, 16, M.flat(M.col(C.grey4)));
  m.cylinder(44, 24, 20, 34, 2, 6, { side: dark });
  return m;
}

export function glyphSprite(name) {
  const g = GLYPHS[name];
  if (!g) return null;
  const w = 16, h = g.length;
  const data = new Uint8ClampedArray(w * h * 4);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = g[y][x];
      if (ch === '.') continue;
      let ci;
      if (ch >= 'A') ci = 10 + (ch.charCodeAt(0) - 65) + 6;
      else ci = parseInt(ch, 16);
      const idx = (y * w + x) * 4;
      data[idx] = PALETTE[ci][0];
      data[idx + 1] = PALETTE[ci][1];
      data[idx + 2] = PALETTE[ci][2];
      data[idx + 3] = 255;
    }
  }
  return { data, w, h, ax: w / 2, ay: h / 2 };
}
